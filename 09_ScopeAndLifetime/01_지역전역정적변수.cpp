#include <iostream>

/*
    변수의 범위(Scope)와 생명주기(Lifetime)

    범위   : 코드에서 변수를 이름으로 접근할 수 있는 영역
    생명주기: 변수가 메모리에 만들어져 살아 있는 기간

    지역 변수      : 선언된 블록 안에서만 접근, 블록을 나가면 사라진다.
    전역 변수      : 함수 밖에 선언, 프로그램이 시작될 때 만들어져 종료될 때 사라진다.
    정적 지역 변수 : 함수 안에서만 접근하지만, 프로그램 종료까지 값을 유지한다.
*/

// 전역 변수: 함수 밖에 선언한다.
// 이 파일에서는 아래에 있는 함수와 main()에서 접근할 수 있다.
int globalVisitCount = 0;

void VisitRoom()
{
    // 지역 변수: VisitRoom()이 호출될 때 만들어지고, 함수가 끝나면 사라진다.
    // 따라서 함수를 다시 호출해도 매번 0부터 시작한다.
    int localVisitCount = 0;

    // 정적 지역 변수: 처음 VisitRoom()에 도착했을 때 한 번만 만들어진다.
    // 함수가 끝나도 사라지지 않아 다음 호출에서도 이전 값을 기억한다.
    // 하지만 이름으로 접근할 수 있는 범위는 이 함수 안으로 제한된다.
    static int staticVisitCount = 0;

    ++localVisitCount;
    ++staticVisitCount;
    ++globalVisitCount;

    std::cout << "지역 변수: " << localVisitCount
        << " | 정적 지역 변수: " << staticVisitCount
        << " | 전역 변수: " << globalVisitCount << '\n';
}

int main()
{
    std::cout << "VisitRoom()을 세 번 호출합니다.\n";
    VisitRoom();
    VisitRoom();
    VisitRoom();

    /*
        출력 결과

        지역 변수: 1 | 정적 지역 변수: 1 | 전역 변수: 1
        지역 변수: 1 | 정적 지역 변수: 2 | 전역 변수: 2
        지역 변수: 1 | 정적 지역 변수: 3 | 전역 변수: 3

        지역 변수는 함수 호출이 끝날 때마다 사라져 매번 1이다.
        정적 지역 변수와 전역 변수는 프로그램이 끝날 때까지 살아 있으므로 값이 누적된다.
    */

    {
        // 블록 지역 변수도 블록을 나가면 사라진다.
        int blockVariable = 10;
        std::cout << "블록 안의 지역 변수: " << blockVariable << '\n';
    }
    // std::cout << blockVariable; // 오류: 블록을 벗어나면 이름으로 접근할 수 없다.

    /*
        정적 지역 변수와 전역 변수의 차이

        공통점: 둘 다 프로그램 종료까지 값을 유지한다.
        차이점: 전역 변수는 여러 함수에서 접근할 수 있지만,
                정적 지역 변수는 선언된 함수 안에서만 접근할 수 있다.

        전역 변수는 어디에서나 값이 바뀔 수 있어 프로그램이 커질수록 추적하기 어렵다.
        꼭 필요한 경우가 아니라면 함수 매개변수, 반환값, 구조체 등을 우선 고려한다.
    */

    return 0;
}
